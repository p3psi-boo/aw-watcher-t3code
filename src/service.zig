const std = @import("std");
const builtin = @import("builtin");
const Config = @import("config.zig").Config;
const Io = std.Io;
const Allocator = std.mem.Allocator;
const label = "io.activitywatch.aw-watcher-t3code";
const unit = "aw-watcher-t3code.service";
const marker = "Generated by aw-watcher-t3code service install.";
const Platform = enum { linux, macos };
const usage =
    \\aw-watcher-t3code service install [watcher flags]
    \\aw-watcher-t3code service start|stop|restart|status|uninstall
    \\install --dry-run prints configuration without installing it.
    \\stop disables login startup; start enables it again.
    \\Externally managed services are never overwritten or removed.
    \\
;

const Layout = struct {
    platform: Platform,
    config: []const u8,
    logs: []const u8,
    domain: []const u8,
};

fn paths(a: Allocator, platform: Platform, home: []const u8, config_home: ?[]const u8, uid: u32) !Layout {
    if (platform == .linux) {
        if (config_home) |p| if (!std.fs.path.isAbsolute(p)) return error.ConfigHomeMustBeAbsolute;
    }
    return switch (platform) {
        .linux => .{
            .platform = platform,
            .config = if (config_home) |p| try std.fs.path.join(a, &.{ p, "systemd/user", unit }) else try std.fs.path.join(a, &.{ home, ".config/systemd/user", unit }),
            .logs = "",
            .domain = "",
        },
        .macos => .{
            .platform = platform,
            .config = try std.fs.path.join(a, &.{ home, "Library/LaunchAgents", label ++ ".plist" }),
            .logs = try std.fs.path.join(a, &.{ home, "Library/Logs/aw-watcher-t3code" }),
            .domain = try std.fmt.allocPrint(a, "gui/{d}", .{uid}),
        },
    };
}

fn quote(a: Allocator, out: *std.ArrayList(u8), text: []const u8, platform: Platform, command_arg: bool) !void {
    if (platform == .linux) try out.append(a, '"');
    for (text) |ch| {
        if (ch == 0) return error.InvalidServiceArgument;
        if (platform == .macos) {
            try out.appendSlice(a, switch (ch) {
                '&' => "&amp;",
                '<' => "&lt;",
                '>' => "&gt;",
                '"' => "&quot;",
                '\'' => "&apos;",
                1...8, 11, 12, 14...31 => return error.InvalidServiceArgument,
                else => &.{ch},
            });
        } else switch (ch) {
            '%' => try out.appendSlice(a, "%%"),
            '$' => try out.appendSlice(a, if (command_arg) "$$" else "$"),
            '\\' => try out.appendSlice(a, "\\\\"),
            '"' => try out.appendSlice(a, "\\\""),
            '\n' => try out.appendSlice(a, "\\n"),
            '\r' => try out.appendSlice(a, "\\r"),
            '\t' => try out.appendSlice(a, "\\t"),
            else => try out.append(a, ch),
        }
    }
    if (platform == .linux) try out.append(a, '"');
}

fn render(a: Allocator, layout: Layout, args: []const []const u8, home: []const u8) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(a);
    switch (layout.platform) {
        .linux => {
            try out.appendSlice(a, "# " ++ marker ++ "\n[Unit]\nDescription=T3 Code activity watcher for ActivityWatch\n\n[Service]\nType=exec\nExecStart=");
            for (args, 0..) |arg, i| {
                if (i != 0) try out.append(a, ' ');
                try quote(a, &out, arg, .linux, true);
            }
            try out.appendSlice(a, "\nEnvironment=");
            const env = try std.fmt.allocPrint(a, "HOME={s}", .{home});
            defer a.free(env);
            try quote(a, &out, env, .linux, false);
            try out.appendSlice(a, "\nRestart=always\nRestartSec=5s\nStandardOutput=journal\nStandardError=journal\n\n[Install]\nWantedBy=default.target\n");
        },
        .macos => {
            try out.appendSlice(a, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- " ++ marker ++ " -->\n<plist version=\"1.0\"><dict>\n<key>Label</key><string>" ++ label ++ "</string>\n<key>ProgramArguments</key><array>\n");
            for (args) |arg| {
                try out.appendSlice(a, "<string>");
                try quote(a, &out, arg, .macos, true);
                try out.appendSlice(a, "</string>\n");
            }
            try out.appendSlice(a, "</array>\n<key>EnvironmentVariables</key><dict><key>HOME</key><string>");
            try quote(a, &out, home, .macos, false);
            try out.appendSlice(a, "</string></dict>\n<key>RunAtLoad</key><true/>\n<key>KeepAlive</key><true/>\n<key>StandardOutPath</key><string>");
            try quote(a, &out, layout.logs, .macos, false);
            try out.appendSlice(a, "/stdout.log</string>\n<key>StandardErrorPath</key><string>");
            try quote(a, &out, layout.logs, .macos, false);
            try out.appendSlice(a, "/stderr.log</string>\n</dict></plist>\n");
        },
    }
    return out.toOwnedSlice(a);
}

fn arguments(a: Allocator, executable: []const u8, c: Config) ![]const []const u8 {
    var args: std.ArrayList([]const u8) = .empty;
    try args.appendSlice(a, &.{ executable, "--base-dir", c.base_dir, "--aw-url", c.aw_url, "--hostname", c.hostname });
    for ([_]struct { []const u8, u64 }{
        .{ "--heartbeat-interval", c.heartbeat_ms }, .{ "--pulsetime", c.pulse_ms },
        .{ "--focus-window", c.focus_ms },           .{ "--timeout", c.timeout_ms },
    }) |item| {
        try args.append(a, item[0]);
        try args.append(a, try std.fmt.allocPrint(a, "{d}ms", .{item[1]}));
    }
    if (c.verbose) try args.append(a, "--verbose");
    return args.toOwnedSlice(a);
}

fn owned(a: Allocator, io: Io, path: []const u8, platform: Platform) ![]u8 {
    const stat = try Io.Dir.cwd().statFile(io, path, .{ .follow_symlinks = false });
    if (stat.kind != .file) return error.ExternallyManagedService;
    const file = try Io.Dir.cwd().openFile(io, path, .{ .follow_symlinks = false, .allow_directory = false });
    defer file.close(io);
    var buffer: [4096]u8 = undefined;
    var reader = file.reader(io, &buffer);
    const data = try reader.interface.allocRemaining(a, .limited(1024 * 1024));
    errdefer a.free(data);
    const prefix = switch (platform) {
        .linux => "# " ++ marker ++ "\n",
        .macos => "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- " ++ marker ++ " -->\n",
    };
    if (!std.mem.startsWith(u8, data, prefix)) return error.ExternallyManagedService;
    return data;
}

fn command(a: Allocator, io: Io, argv: []const []const u8, display: bool) !std.process.RunResult {
    const result = try std.process.run(a, io, .{
        .argv = argv,
        .stdout_limit = .limited(1024 * 1024),
        .stderr_limit = .limited(64 * 1024),
        .timeout = .{ .duration = .{ .clock = .awake, .raw = .fromSeconds(30) } },
    });
    if (display) {
        try Io.File.stdout().writeStreamingAll(io, result.stdout);
        try Io.File.stderr().writeStreamingAll(io, result.stderr);
    }
    return result;
}

fn checked(a: Allocator, io: Io, argv: []const []const u8) !void {
    const result = try command(a, io, argv, true);
    if (!result.term.success()) return error.ServiceCommandFailed;
}

fn start(a: Allocator, io: Io, layout: Layout) !void {
    if (layout.platform == .linux) {
        try checked(a, io, &.{ "systemctl", "--user", "daemon-reload" });
        return checked(a, io, &.{ "systemctl", "--user", "enable", "--now", unit });
    }
    const target = try std.fmt.allocPrint(a, "{s}/{s}", .{ layout.domain, label });
    try checked(a, io, &.{ "launchctl", "enable", target });
    const loaded = try command(a, io, &.{ "launchctl", "print", target }, false);
    if (loaded.term.success()) return checked(a, io, &.{ "launchctl", "kickstart", target });
    try checked(a, io, &.{ "launchctl", "bootstrap", layout.domain, layout.config });
}

fn stop(a: Allocator, io: Io, layout: Layout) !void {
    if (layout.platform == .linux) return checked(a, io, &.{ "systemctl", "--user", "disable", "--now", unit });
    const target = try std.fmt.allocPrint(a, "{s}/{s}", .{ layout.domain, label });
    try checked(a, io, &.{ "launchctl", "disable", target });
    const loaded = try command(a, io, &.{ "launchctl", "print", target }, false);
    if (loaded.term.success()) try checked(a, io, &.{ "launchctl", "bootout", target });
}

pub fn run(allocator: Allocator, io: Io, args: []const []const u8, config: Config, executable: []const u8, home: []const u8, config_home: ?[]const u8) !void {
    if (config.help or args.len == 0) return Io.File.stdout().writeStreamingAll(io, usage);
    if (args.len != 1) return error.InvalidServiceCommand;
    const action = args[0];
    const install = std.mem.eql(u8, action, "install");
    if (!install and !std.mem.eql(u8, action, "start") and !std.mem.eql(u8, action, "stop") and !std.mem.eql(u8, action, "restart") and !std.mem.eql(u8, action, "status") and !std.mem.eql(u8, action, "uninstall")) return error.InvalidServiceCommand;
    if (config.dry_run and !install) return error.DryRunOnlySupportsInstall;
    var arena = std.heap.ArenaAllocator.init(allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const platform: Platform = switch (builtin.os.tag) {
        .linux => .linux,
        .macos => .macos,
        else => return error.UnsupportedServicePlatform,
    };
    const uid: u32 = if (builtin.os.tag == .linux) std.os.linux.getuid() else std.c.getuid();
    const layout = try paths(a, platform, home, config_home, uid);
    if (install) {
        var c = config;
        const cwd = try std.process.currentPathAlloc(io, a);
        c.base_dir = try std.fs.path.resolve(a, &.{ cwd, c.base_dir });
        const exe = try std.fs.path.resolve(a, &.{ cwd, executable });
        const data = try render(a, layout, try arguments(a, exe, c), home);
        if (c.dry_run) return Io.File.stdout().writeStreamingAll(io, data);
        if (owned(a, io, layout.config, platform)) |existing| {
            if (!std.mem.eql(u8, existing, data)) return error.ServiceAlreadyInstalledWithDifferentOptions;
            return Io.File.stdout().writeStreamingAll(io, "Service already installed. Use service start or service status.\n");
        } else |err| switch (err) {
            error.FileNotFound => {},
            else => return err,
        }
        if (platform == .linux) {
            const result = try command(a, io, &.{ "systemctl", "--user", "show", unit, "--property=LoadState", "--value" }, false);
            if (!result.term.success()) return error.ServiceManagerUnavailable;
            if (!std.mem.eql(u8, std.mem.trim(u8, result.stdout, " \r\n\t"), "not-found")) return error.ExternallyManagedService;
        } else {
            const domain = try command(a, io, &.{ "launchctl", "print", layout.domain }, false);
            if (!domain.term.success()) return error.ServiceManagerUnavailable;
            const target = try std.fmt.allocPrint(a, "{s}/{s}", .{ layout.domain, label });
            const loaded = try command(a, io, &.{ "launchctl", "print", target }, false);
            if (loaded.term.success()) return error.ExternallyManagedService;
        }
        _ = try Io.Dir.cwd().createDirPathStatus(io, std.fs.path.dirname(layout.config).?, @fromBackingInt(@intCast(0o700)));
        if (platform == .macos) _ = try Io.Dir.cwd().createDirPathStatus(io, layout.logs, @fromBackingInt(@intCast(0o700)));
        const file = try Io.Dir.cwd().createFile(io, layout.config, .{ .exclusive = true, .permissions = @fromBackingInt(@intCast(0o600)) });
        file.writeStreamingAll(io, data) catch |err| {
            file.close(io);
            try Io.Dir.cwd().deleteFile(io, layout.config);
            return err;
        };
        file.close(io);
        start(a, io, layout) catch |err| {
            try Io.File.stderr().writeStreamingAll(io, "Configuration saved. Inspect service status, then retry service start.\n");
            return err;
        };
        return Io.File.stdout().writeStreamingAll(io, "Service installed and startup requested. Use service status to inspect it.\n");
    }
    _ = try owned(a, io, layout.config, platform);
    if (std.mem.eql(u8, action, "start")) return start(a, io, layout);
    if (std.mem.eql(u8, action, "stop")) return stop(a, io, layout);
    if (std.mem.eql(u8, action, "restart")) {
        if (platform == .linux) {
            try checked(a, io, &.{ "systemctl", "--user", "daemon-reload" });
            return checked(a, io, &.{ "systemctl", "--user", "restart", unit });
        }
        const target = try std.fmt.allocPrint(a, "{s}/{s}", .{ layout.domain, label });
        const loaded = try command(a, io, &.{ "launchctl", "print", target }, false);
        if (loaded.term.success()) return checked(a, io, &.{ "launchctl", "kickstart", "-k", target });
        return start(a, io, layout);
    }
    if (std.mem.eql(u8, action, "status")) {
        const detail = try std.fmt.allocPrint(a, "Configuration: {s}\nLogs: {s}\n", .{ layout.config, if (platform == .linux) "journalctl --user -u " ++ unit else layout.logs });
        try Io.File.stdout().writeStreamingAll(io, detail);
        if (platform == .linux) return checked(a, io, &.{ "systemctl", "--user", "status", "--no-pager", unit });
        return checked(a, io, &.{ "launchctl", "print", try std.fmt.allocPrint(a, "{s}/{s}", .{ layout.domain, label }) });
    }
    try stop(a, io, layout);
    try Io.Dir.cwd().deleteFile(io, layout.config);
    if (platform == .linux) try checked(a, io, &.{ "systemctl", "--user", "daemon-reload" });
    try Io.File.stdout().writeStreamingAll(io, "Service removed. Binaries, logs and ActivityWatch data were preserved.\n");
}

test "Linux and macOS rendering preserve literal arguments" {
    const a = std.testing.allocator;
    var arena = std.heap.ArenaAllocator.init(a);
    defer arena.deinit();
    const temp = arena.allocator();
    const c: Config = .{ .base_dir = "/data/会话%/$HOME & \"quote\"", .aw_url = "http://localhost:5600", .hostname = "host", .verbose = true };
    const args = try arguments(temp, "/bin/my watcher", c);
    try std.testing.expectEqualStrings("--verbose", args[args.len - 1]);
    try std.testing.expectEqualStrings("1000ms", args[8]);
    const linux = try render(temp, try paths(temp, .linux, "/home/user", null, 1000), args, "/home/user");
    try std.testing.expect(std.mem.indexOf(u8, linux, "会话%%/$$HOME & \\\"quote\\\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, linux, "\"/bin/my watcher\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, linux, "Environment=\"HOME=/home/user\"") != null);
    const macos = try render(temp, try paths(temp, .macos, "/Users/user", null, 501), args, "/Users/user");
    try std.testing.expect(std.mem.indexOf(u8, macos, "<string>/data/会话%/$HOME &amp; &quot;quote&quot;</string>") != null);
    try std.testing.expect(std.mem.indexOf(u8, macos, "<key>Label</key><string>" ++ label ++ "</string>") != null);
    try std.testing.expectError(error.ConfigHomeMustBeAbsolute, paths(temp, .linux, "/home/user", "relative", 0));
    try std.testing.expectError(error.InvalidServiceArgument, render(temp, try paths(temp, .linux, "/home/user", null, 0), &.{"bad\x00arg"}, "/home/user"));
}

test "service ownership rejects external files and symlinks" {
    const a = std.testing.allocator;
    const io = std.testing.io;
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    const root = try tmp.dir.realPathFileAlloc(io, ".", a);
    defer a.free(root);
    const path = try std.fs.path.join(a, &.{ root, "service" });
    defer a.free(path);
    try tmp.dir.writeFile(io, .{ .sub_path = "service", .data = "external configuration" });
    try std.testing.expectError(error.ExternallyManagedService, owned(a, io, path, .linux));
    try tmp.dir.deleteFile(io, "service");
    try tmp.dir.writeFile(io, .{ .sub_path = "target", .data = "# " ++ marker ++ "\n" });
    try tmp.dir.symLink(io, "target", "service", .{});
    try std.testing.expectError(error.ExternallyManagedService, owned(a, io, path, .linux));
    try tmp.dir.deleteFile(io, "service");
    try tmp.dir.writeFile(io, .{ .sub_path = "service", .data = "# " ++ marker ++ "\n" });
    const data = try owned(a, io, path, .linux);
    defer a.free(data);
    try std.testing.expectEqualStrings("# " ++ marker ++ "\n", data);
}

test "invalid service actions cannot change services" {
    try std.testing.expectError(error.InvalidServiceCommand, run(std.testing.allocator, std.testing.io, &.{"unknown"}, .{ .base_dir = "/data", .aw_url = "http://localhost:5600", .hostname = "host" }, "/bin/watcher", "/home/user", null));
    try std.testing.expectError(error.DryRunOnlySupportsInstall, run(std.testing.allocator, std.testing.io, &.{"stop"}, .{ .base_dir = "/data", .aw_url = "http://localhost:5600", .hostname = "host", .dry_run = true }, "/bin/watcher", "/home/user", null));
}
